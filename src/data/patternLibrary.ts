export const create5In5Out = (length = 300): boolean[] => {
  return Array.from({ length }, (_, i) => (i % 10) < 5);
};

export const createThreadingArray = (type: string, length = 300): boolean[] => {
  const clean = type.toLowerCase();
  if (clean.includes('boş') || clean.includes('out') || clean.includes('empty')) {
    return Array.from({ length }, () => false);
  }
  if (clean.includes('5-5') || clean.includes('5-in 5-out') || clean.includes('5 dolu 5 boş') || clean.includes('5 dolu 5 beş')) {
    return create5In5Out(length);
  }
  return Array.from({ length }, (_, i) => {
    if (clean.includes('full') || clean.includes('all')) return true;
    if (clean.includes('1-1') || clean.includes('1-in 1-out') || clean.includes('1-dolu 1-boş')) return i % 2 === 0;
    if (clean.includes('1-3') || clean.includes('1-in 3-out') || clean.includes('1-dolu 3-boş')) return i % 4 === 0;
    if (clean.includes('3-1') || clean.includes('3-in 1-out')) return i % 4 !== 3;
    return i % 2 === 0;
  });
};

